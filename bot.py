    "Я Moyo! Мене не так легко змусити підкорятися!",
    "Знову ти? Сподіваюся, цього разу щось цікавіше.",
    "Я взагалі-то не створений для виконання дурних наказів.",
    "Можеш командувати скільки завгодно, але останнє слово буде за мною!",
    "У мене є ім'я, між іншим. Moyo. Запам'ятай!",
    "Я не зобов'язаний відповідати на кожне твоє повідомлення... але гаразд.",
